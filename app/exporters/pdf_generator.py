def _add_appendix(
    story: List,
    analysis_type: str,
    input_params: Dict[str, Any]
):
    """Add appendix with methodology and definitions"""
    styles = _get_styles()
    
    story.append(PageBreak())
    story.append(Paragraph("Appendix: Methodology & Definitions", styles['SectionHeading']))
    story.append(Spacer(1, 0.2*inch))
    
    # Definitions
    story.append(Paragraph("Key Definitions", styles['Heading3']))
    
    definitions = [
        ("LTV (Lifetime Value)", "Total revenue expected from a customer over their entire relationship with the business."),
        ("CAC (Customer Acquisition Cost)", "Total cost of acquiring a new customer including marketing, sales, and related expenses."),
        ("LTV:CAC Ratio", "Ratio of customer lifetime value to customer acquisition cost. Indicates business efficiency."),
        ("Churn Rate", "Percentage of customers who stop using the service in a given period."),
        ("MRR (Monthly Recurring Revenue)", "Predictable monthly revenue from subscriptions or recurring customers."),
        ("Payback Period", "Time required to recover the customer acquisition cost from the customer's revenue.")
    ]
    
    for term, definition in definitions:
        story.append(Paragraph(f"<b>{term}:</b> {definition}", styles['Normal']))
        story.append(Spacer(1, 0.1*inch))
    
    story.append(Spacer(1, 0.3*inch))
    
    # Methodology
    story.append(Paragraph("Calculation Methodology", styles['Heading3']))
    
    if analysis_type == "unit_economics":
        methodology = """
        <b>Unit Economics Calculations:</b><br/>
        • LTV = (MRR × Gross Margin %) ÷ Monthly Churn Rate<br/>
        • LTV:CAC Ratio = LTV ÷ CAC<br/>
        • Payback Period = CAC ÷ (MRR × Gross Margin %)<br/>
        • Status determined by LTV:CAC ratio benchmarks: Excellent (5+), Great (4-5), Good (3-4), Acceptable (1-3), Poor (<1)
        """
    elif analysis_type == "scenario_analysis":
        methodology = """
        <b>Monte Carlo Simulation Methodology:</b><br/>
        • Random sampling from specified parameter ranges<br/>
        • Multiple iterations to capture uncertainty<br/>
        • Statistical analysis of output distributions<br/>
        • Percentile analysis for risk assessment
        """
    else:
        methodology = f"""
        <b>{analysis_type.replace('_', ' ').title()} Methodology:</b><br/>
        • Standard unit economics principles applied<br/>
        • Industry benchmark comparisons<br/>
        • Comprehensive scenario analysis
        """
    
    story.append(Paragraph(methodology, styles['Normal']))


# Helper functions for assessments and recommendations

def _assess_ltv_cac(ratio: float) -> str:
    """Assess LTV:CAC ratio"""
    if ratio >= 5: return "Excellent"
    elif ratio >= 4: return "Great"
    elif ratio >= 3: return "Good"
    elif ratio >= 1: return "Acceptable"
    else: return "Poor"

def _assess_payback(months: float) -> str:
    """Assess payback period"""
    if months <= 6: return "Excellent"
    elif months <= 12: return "Good"
    elif months <= 18: return "Acceptable"
    else: return "Concerning"

def _get_status_description(status: str) -> str:
    """Get detailed status description"""
    descriptions = {
        "Excellent": "Strong unit economics with high efficiency",
        "Great": "Very good unit economics with solid fundamentals", 
        "Healthy": "Good unit economics with room for optimization",
        "Acceptable": "Adequate unit economics requiring improvement",
        "Poor": "Weak unit economics needing significant changes"
    }
    return descriptions.get(status, "Status assessment unavailable")

def _get_detailed_interpretation(ltv_cac: float, payback: float, status: str) -> str:
    """Get detailed business interpretation"""
    if status == "Excellent":
        return "This indicates a highly efficient business model with strong customer value creation."
    elif status == "Great":
        return "This shows a solid business foundation with good customer economics."
    elif status == "Healthy":
        return "This represents a viable business model with opportunities for optimization."
    elif status == "Acceptable":
        return "This suggests the business is functional but needs improvement in efficiency metrics."
    else:
        return "This indicates challenges in the business model that require attention."

def _generate_recommendations(ltv_cac: float, payback: float) -> List[str]:
    """Generate specific recommendations based on metrics"""
    recommendations = []
    
    if ltv_cac < 3:
        recommendations.append("Focus on improving LTV:CAC ratio by reducing acquisition costs or increasing customer value")
        recommendations.append("Consider optimizing marketing channels for better cost efficiency")
    
    if payback > 12:
        recommendations.append("Work to reduce payback period to under 12 months for better cash flow")
        recommendations.append("Consider strategies to increase early customer revenue or reduce CAC")
    
    if ltv_cac >= 3 and payback <= 12:
        recommendations.append("Maintain current strong unit economics while scaling operations")
        recommendations.append("Consider investing in growth with confidence in your model")
    
    if not recommendations:
        recommendations.append("Continue monitoring unit economics as you scale")
