import matplotlib
matplotlib.use('Agg')  # Use non-interactive backend


def generate_pdf_report(
    analysis_type: str,
    input_params: Dict[str, Any],
    results: Dict[str, Any],
    title: Optional[str] = None,
    description: Optional[str] = None,
    include_charts: bool = True
) -> bytes:
    """
    Generate comprehensive PDF report for analysis
    
    Args:
        analysis_type: Type of analysis
        input_params: Input parameters
        results: Analysis results
        title: Optional custom title
        description: Optional description
        include_charts: Whether to include visualizations
    
    Returns:
        PDF as bytes
    """
    
    # Create PDF buffer
    buffer = io.BytesIO()
    
    # Create document
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=72,
        leftMargin=72,
        topMargin=72,
        bottomMargin=18
    )
    
    # Build story (content elements)
    story = []
    
    # Add title page
    _add_title_page(story, analysis_type, title, description)
    
    # Add executive summary
    _add_executive_summary(story, analysis_type, input_params, results)
    
    # Add detailed analysis based on type
    if analysis_type == "unit_economics":
        _add_unit_economics_analysis(story, input_params, results, include_charts)
    elif analysis_type == "pricing_tiers":
        _add_pricing_tiers_analysis(story, input_params, results, include_charts)
    elif analysis_type == "freemium_funnel":
        _add_freemium_funnel_analysis(story, input_params, results, include_charts)
    elif analysis_type == "scenario_analysis":
        _add_scenario_analysis_report(story, input_params, results, include_charts)
    
    # Add appendix
    _add_appendix(story, analysis_type, input_params)
    
    # Build PDF
    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()


def _get_styles():
    """Get custom paragraph styles"""
    styles = getSampleStyleSheet()
    
    # Custom styles
    styles.add(ParagraphStyle(
        name='CustomTitle',
        parent=styles['Heading1'],
        fontSize=24,
        spaceAfter=30,
        alignment=TA_CENTER,
        textColor=colors.darkblue
    ))
    
    styles.add(ParagraphStyle(
        name='SectionHeading',
        parent=styles['Heading2'],
        fontSize=16,
        spaceAfter=12,
        textColor=colors.darkblue,
        borderWidth=1,
        borderColor=colors.darkblue,
        borderPadding=5
    ))
    
    styles.add(ParagraphStyle(
        name='MetricValue',
        parent=styles['Normal'],
        fontSize=14,
        textColor=colors.darkgreen,
        alignment=TA_CENTER,
        spaceAfter=6
    ))
    
    return styles


def _add_title_page(
    story: List,
    analysis_type: str,
    title: Optional[str],
    description: Optional[str]
):
    """Add title page to PDF report"""
    styles = _get_styles()
    
    # Main title
    main_title = title or f"{analysis_type.replace('_', ' ').title()} Analysis Report"
    story.append(Paragraph(main_title, styles['CustomTitle']))
    story.append(Spacer(1, 0.5*inch))
    
    # UnitSim branding
    story.append(Paragraph("Generated by UnitSim 2.0", styles['Heading3']))
    story.append(Paragraph("Advanced Unit Economics Analysis Platform", styles['Normal']))
    story.append(Spacer(1, 0.3*inch))
    
    # Report metadata
    metadata_data = [
        ['Report Type:', analysis_type.replace('_', ' ').title()],
        ['Generated:', datetime.now().strftime('%B %d, %Y at %I:%M %p')],
        ['Version:', 'UnitSim 2.0'],
        ['Format:', 'Comprehensive Analysis Report']
    ]
    
    metadata_table = Table(metadata_data, colWidths=[2*inch, 3*inch])
    metadata_table.setStyle(TableStyle([
        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
        ('FONTNAME', (0, 0), (0, -1), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, -1), 10),
        ('GRID', (0, 0), (-1, -1), 1, colors.lightgrey)
    ]))
    
    story.append(metadata_table)
    story.append(Spacer(1, 0.5*inch))
    
    # Description if provided
    if description:
        story.append(Paragraph("Report Description", styles['Heading3']))
        story.append(Paragraph(description, styles['Normal']))
        story.append(Spacer(1, 0.3*inch))
    
    # Disclaimer
    disclaimer = """
    <b>Important Notice:</b> This report is generated based on the input parameters provided 
    and uses standard unit economics calculations. Results should be validated against actual 
    business data and used as part of a comprehensive business analysis framework.
    """
    story.append(Paragraph(disclaimer, styles['Normal']))
    
    story.append(PageBreak())


def _add_executive_summary(
    story: List,
    analysis_type: str,
    input_params: Dict[str, Any],
    results: Dict[str, Any]
):
    """Add executive summary section"""
    styles = _get_styles()
    
    story.append(Paragraph("Executive Summary", styles['SectionHeading']))
    story.append(Spacer(1, 0.2*inch))
    
    # Key findings based on analysis type
    if analysis_type == "unit_economics":
        _add_unit_economics_summary(story, results)
    elif analysis_type == "pricing_tiers":
        _add_pricing_tiers_summary(story, results)
    elif analysis_type == "freemium_funnel":
        _add_freemium_funnel_summary(story, results)
    elif analysis_type == "scenario_analysis":
        _add_scenario_analysis_summary(story, results)
    
    story.append(Spacer(1, 0.3*inch))


def _add_unit_economics_summary(story: List, results: Dict[str, Any]):
    """Add unit economics executive summary"""
    styles = _get_styles()
    
    ltv = results.get('ltv', 0)
    ltv_cac_ratio = results.get('ltv_cac_ratio', 0)
    payback_months = results.get('payback_months', 0)
    status = results.get('status', 'Unknown')
    
    # Key metrics table
    summary_data = [
        ['Metric', 'Value', 'Assessment'],
        ['Customer Lifetime Value (LTV)', f'${ltv:,.2f}', ''],
        ['LTV:CAC Ratio', f'{ltv_cac_ratio:.2f}', _assess_ltv_cac(ltv_cac_ratio)],
        ['Payback Period', f'{payback_months:.1f} months', _assess_payback(payback_months)],
        ['Overall Status', status, _get_status_description(status)]
    ]
    
    summary_table = Table(summary_data, colWidths=[2.5*inch, 1.5*inch, 2.5*inch])
    summary_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.darkblue),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, -1), 10),
        ('GRID', (0, 0), (-1, -1), 1, colors.black)
    ]))
    
    story.append(summary_table)
    
    # Interpretation
    interpretation = f"""
    <b>Key Finding:</b> Your unit economics show a {status.lower()} business model with an LTV:CAC ratio of {ltv_cac_ratio:.2f}. 
    {_get_detailed_interpretation(ltv_cac_ratio, payback_months, status)}
    """
    story.append(Spacer(1, 0.2*inch))
    story.append(Paragraph(interpretation, styles['Normal']))


